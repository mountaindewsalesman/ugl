"""Sample English text from several open datasets into data/raw/<source>/.

Wikipedia is one register (encyclopedic, third person, past tense, dense with
names and dates).  A language model trained only on it learns that register.
These sources cover the others; each is openly licensed and human-written
unless noted.

    fineweb-edu    educational web pages (explanations, how-tos, lessons)   ODC-By
    simplewiki     Simple English Wikipedia (short, plain sentences)       CC BY-SA
    gutenberg      public-domain books (narrative, dialogue, older style)  public domain
    news           CC-News articles (reporting, quotes, present tense)     CC-News terms (research)
    dialogue       OpenAssistant oasst1 messages (questions, answers,      Apache-2.0
                   second person, imperatives; written by volunteers)
    tinystories    children's stories (very simple)                         CDLA-Sharing
    tinystories-train  the same, from the 2.7M-story training file (streamed; shard with --offset)
                   NOTE: generated by GPT-3.5/4, not human-written

    python scripts/fetch_sources.py --docs 300                 # every source
    python scripts/fetch_sources.py fineweb-edu news --docs 2000

Output: data/raw/<source>/<source>-<offset>.jsonl, one document per line,
{"title": ..., "text": "paragraphs separated by newlines", "source": ...}
(the format ugl.corpus.documents reads).  Only the parquet row groups needed
are downloaded, never whole datasets.
"""
import argparse
import json
import os
import random
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "data", "raw")


def unwrap(text):
    """Hard-wrapped plain text (blank line between paragraphs) -> one paragraph per line."""
    paras = re.split(r"\n\s*\n", text.replace("\r", ""))
    return "\n".join(re.sub(r"\s+", " ", p).strip() for p in paras if p.strip())


def gutenberg_excerpt(text, rng, n=40):
    """A run of n prose paragraphs from the middle of a book, without the
    licence header/footer, chapter headings or tables of contents."""
    m = re.search(r"\*\*\* ?START OF.*?\*\*\*", text)
    e = re.search(r"\*\*\* ?END OF", text)
    text = text[m.end() if m else 0: e.start() if e else len(text)]
    paras = [p for p in unwrap(text).split("\n")
             if len(p) > 80 and not p.isupper() and not re.match(r"(CHAPTER|BOOK|PART)\b", p, re.I)]
    if len(paras) < n:
        return "\n".join(paras)
    start = rng.randrange(len(paras) // 4, len(paras) - n) if len(paras) > 2 * n else 0
    return "\n".join(paras[start:start + n])


def parquet_rows(path, columns, need, row_group=0):
    """Rows of one dataset parquet file, reading row groups from row_group on
    until `need` rows have been read."""
    import pyarrow.parquet as pq
    from huggingface_hub import HfFileSystem
    f = pq.ParquetFile(HfFileSystem().open("datasets/" + path))
    got = 0
    for g in range(row_group, f.num_row_groups):
        t = f.read_row_group(g, columns=columns).to_pylist()
        for row in t:
            yield row
            got += 1
            if got >= need:
                return


def fineweb(n, offset, rng):
    for r in parquet_rows("HuggingFaceFW/fineweb-edu/sample/10BT/000_00000.parquet", ["text", "url"], n, offset):
        yield None, r["text"]


def simplewiki(n, offset, rng):
    for r in parquet_rows("wikimedia/wikipedia/20231101.simple/train-00000-of-00001.parquet", ["title", "text"], n, offset):
        # drop section headings and list/table residue: keep lines that end like sentences
        text = "\n".join(l for l in r["text"].split("\n") if re.search(r"[.!?]\"?$", l.strip()))
        yield r["title"], text


def gutenberg(n, offset, rng):
    for r in parquet_rows("manu/project_gutenberg/data/en-00000-of-00052-7cda8f63c262acf8.parquet", ["text"], n, offset):
        yield None, gutenberg_excerpt(r["text"], rng)


def news(n, offset, rng):
    for r in parquet_rows("vblagoje/cc_news/plain_text/train-00000-of-00005.parquet", ["title", "text"], n, offset):
        yield r["title"], r["text"]


def dialogue(n, offset, rng):
    rows = (r for r in parquet_rows("OpenAssistant/oasst1/data/train-00000-of-00001-b42a775f407cee45.parquet",
                                    ["text", "lang", "role"], 10 ** 9, offset) if r["lang"] == "en")
    for i, r in enumerate(rows):
        if i >= n:
            return
        # code blocks and markdown lists are not sentences
        text = re.sub(r"```.*?```", "", r["text"], flags=re.S)
        text = "\n".join(l for l in text.split("\n") if not re.match(r"\s*([-*#|>]|\d+\.)\s", l))
        yield None, text


def tinystories(n, offset, rng, split="valid"):
    """Stories n from story `offset` on.  split "valid" (~27k stories, 20 MB) or
    "train" (~2.7M stories, 2.2 GB): the file is read as a stream, never whole."""
    from huggingface_hub import hf_hub_download
    path = hf_hub_download("roneneldan/TinyStories", f"TinyStoriesV2-GPT4-{split}.txt", repo_type="dataset")
    k, buf = 0, []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if "<|endoftext|>" not in line:
                buf.append(line)
                continue
            if k >= offset:
                yield None, unwrap("".join(buf))
                if k + 1 >= offset + n:
                    return
            k += 1
            buf = []


def tinystories_train(n, offset, rng):
    return tinystories(n, offset, rng, split="train")


SOURCES = {"fineweb-edu": fineweb, "simplewiki": simplewiki, "gutenberg": gutenberg,
           "news": news, "dialogue": dialogue, "tinystories": tinystories,
           "tinystories-train": tinystories_train}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("sources", nargs="*", help="any of: " + ", ".join(SOURCES) + " (default: all)")
    ap.add_argument("--docs", type=int, default=300, help="documents per source")
    ap.add_argument("--offset", type=int, default=0,
                    help="row group (parquet) or document index (text) to start at: a later offset gives fresh text")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--shards", type=int, default=1,
                    help="write this many consecutive files of --docs documents each, in one pass")
    a = ap.parse_args()
    for name in a.sources or list(SOURCES):
        if name not in SOURCES:
            sys.exit("unknown source %r; choose from %s" % (name, ", ".join(SOURCES)))
        rng = random.Random(a.seed)
        os.makedirs(os.path.join(OUT, name), exist_ok=True)
        docs = SOURCES[name](a.docs * a.shards, a.offset, rng)
        for shard in range(a.shards):
            start = a.offset + shard * a.docs
            path = os.path.join(OUT, name, "%s-%04d.jsonl" % (name, start))
            k = 0
            with open(path, "w", encoding="utf-8") as out:
                for title, text in docs:
                    if text and text.strip():
                        out.write(json.dumps({"title": title, "text": text.strip(), "source": name},
                                             ensure_ascii=False) + "\n")
                        k += 1
                    if k >= a.docs:
                        break
            print("%-12s %5d documents -> %s" % (name, k, os.path.relpath(path, ROOT)), file=sys.stderr)


if __name__ == "__main__":
    main()
